/**
 * แปลงชื่อเครื่องภาษาอังกฤษให้เป็นภาษาไทยที่ถูกต้องตามหลักสากลวิศวกรรมการแพทย์
 * @param englishName ชื่อเครื่องภาษาอังกฤษ (Type_Equpment หรือ Name_Equpment)
 * @param fallbackCategory หมวดหมู่เสริม
 * @returns ชื่อภาษาไทยที่ถูกต้องสละสลวย
 */
export function translateMedicalEquipmentToThai(englishName: string, fallbackCategory?: string): string {
  if (!englishName) return '';
  const cleanName = englishName.trim();
  const upper = cleanName.toUpperCase();

  // 1. ตรวจสอบจาก Dictionary เป๊ะๆ
  if (MEDICAL_EQUIPMENT_TH_DICTIONARY[upper]) {
    return MEDICAL_EQUIPMENT_TH_DICTIONARY[upper];
  }

  // 2. ค้นหาแบบ Substring match จาก Dictionary
  for (const [key, thaiVal] of Object.entries(MEDICAL_EQUIPMENT_TH_DICTIONARY)) {
    if (upper === key || upper.startsWith(key) || key.startsWith(upper)) {
      return thaiVal;
    }
  }

  // 3. กฎแปลคำสำคัญทางวิศวกรรมการแพทย์ตามหมวดหมู่
  if (upper.includes('ANALYZER') || upper.includes('ANALYSIS')) {
    if (upper.includes('BLOOD') || upper.includes('HEMAT')) return 'เครื่องตรวจวิเคราะห์ตัวอย่างเลือดและโลหิตวิทยา';
    if (upper.includes('SKIN')) return 'เครื่องตรวจวิเคราะห์สภาพผิวหนัง';
    if (upper.includes('EYE') || upper.includes('VISUAL')) return 'เครื่องตรวจวิเคราะห์สายตาและโครงสร้างลูกตา';
    if (upper.includes('EAR') || upper.includes('AUDI')) return 'เครื่องตรวจวัดและวิเคราะห์การได้ยิน';
    if (upper.includes('BREATH')) return 'เครื่องตรวจวิเคราะห์ลมหายใจ';
    return 'เครื่องตรวจวิเคราะห์ทางการแพทย์';
  }

  if (upper.includes('ANESTHESIA')) return 'เครื่องดมยาสลบพร้อมระบบช่วยหายใจ';
  if (upper.includes('VENTILATOR')) return 'เครื่องช่วยหายใจสำหรับผู้ป่วยวิกฤต';
  if (upper.includes('MONITOR')) return 'เครื่องเฝ้าระวังและติดตามสัญญาณชีพผู้ป่วย';
  if (upper.includes('DEFIBRILLAT')) return 'เครื่องกระตุกหัวใจด้วยไฟฟ้า';
  if (upper.includes('ELECTROCAR')) return 'เครื่องบันทึกคลื่นไฟฟ้าหัวใจ (ECG/EKG)';
  if (upper.includes('ULTRASOUND') || upper.includes('ULTRASONO')) return 'เครื่องตรวจอวัยวะด้วยคลื่นเสียงความถี่สูง (อัลตราซาวด์)';
  if (upper.includes('X-RAY') || upper.includes('RADIOG')) return 'เครื่องตรวจเอกซเรย์รังสีวินิจฉัย';
  if (upper.includes('SUCTION') || upper.includes('ASPIRAT')) return 'เครื่องดูดเสมหะและของเหลวทางการแพทย์';
  if (upper.includes('INFUSION')) return 'เครื่องควบคุมการให้สารน้ำและยาทางหลอดเลือดดำ';
  if (upper.includes('SYRINGE PUMP')) return 'เครื่องควบคุมการให้ยาทางกระบอกฉีด';
  if (upper.includes('AUTOCLAVE') || upper.includes('STERILIZ')) return 'หม้อนึ่งฆ่าเชื้อด้วยไอน้ำแรงดันสูง';
  if (upper.includes('INCUBATOR')) return 'ตู้อบเด็กทารกแรกเกิด';
  if (upper.includes('ENDOSCOP')) return 'ชุดกล้องส่องตรวจระบบภายในร่างกาย';
  if (upper.includes('MICROSCOP')) return 'กล้องจุลทรรศน์สำหรับงานผ่าตัด';
  if (upper.includes('LASER')) return 'เครื่องเลเซอร์ทางการแพทย์';
  if (upper.includes('DENTAL')) return 'ชุดยูนิตและอุปกรณ์ทันตกรรม';
  if (upper.includes('BED')) return 'เตียงผู้ป่วยระบบไฟฟ้า';
  if (upper.includes('TABLE') && upper.includes('OPERAT')) return 'เตียงผ่าตัดระบบไฟฟ้า';
  if (upper.includes('ALARM')) return 'ระบบแจ้งเตือนและสัญญาณความปลอดภัยทางการแพทย์';
  if (upper.includes('AIR COOL')) return 'ระบบทำความเย็นและควบคุมอุณหภูมิทางการแพทย์';

  // 4. ถ้ามี Category นำ Category มาแปลต่อ
  if (fallbackCategory) {
    const catUpper = fallbackCategory.toUpperCase();
    if (MEDICAL_EQUIPMENT_TH_DICTIONARY[catUpper]) {
      return MEDICAL_EQUIPMENT_TH_DICTIONARY[catUpper];
    }
  }

  // คืนค่ารูปแบบสุภาพ
  return `เครื่องมือแพทย์: ${cleanName}`;
}
